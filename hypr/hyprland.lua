hl.animation({ leaf = "layersOut", enabled = true, speed = 1.0 * a, bezier = "linear", style = "fade" })
hl.animation({ leaf = "fadeLayersIn", enabled = true, speed = 1.0 * a, bezier = "almostLinear" })
hl.animation({ leaf = "fadeLayersOut", enabled = true, speed = 1.0 * a, bezier = "almostLinear" })
