hl.animation({ leaf = "windowsOut", enabled = true, speed = 1.0 * a, bezier = "linear", style = "popin 87%" })
hl.animation({ leaf = "fadeIn", enabled = true, speed = 1.0 * a, bezier = "almostLinear" })
hl.animation({ leaf = "fadeOut", enabled = true, speed = 1.0 * a, bezier = "almostLinear" })
hl.animation({ leaf = "fade", enabled = true, speed = 1.5 * a, bezier = "quick" })
