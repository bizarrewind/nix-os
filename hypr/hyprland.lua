-- Load dynamic colors from Stylix (generated by Home Manager)
local has_colors, colors = pcall(dofile, os.getenv("HOME") .. "/.config/dynamic-colors/hypr.lua")
local active_border_1 = has_colors and colors.active_border_1 or "rgba(c87f3eee)"
local active_border_2 = has_colors and colors.active_border_2 or "rgba(b18a59ee)"
local inactive_border = has_colors and colors.inactive_border or "rgba(14141d88)"

-- Refer to https://wiki.hypr.land/Configuring/Basics/Variables/
hl.config({
	general = {
		gaps_in = 3,
		gaps_out = 2,

		border_size = 2,

		col = {
			-- Active: dynamic stylix accent gradient
			active_border = { colors = { active_border_1, active_border_2 }, angle = 45 },
			-- Inactive: subtle dynamic dark grey
			inactive_border = inactive_border,
		},

		-- Set to true to enable resizing windows by clicking and dragging on borders and gaps
		resize_on_border = true,

		-- Please see https://wiki.hypr.land/Configuring/Advanced-and-Cool/Tearing/ before you turn this on
		allow_tearing = false,

		layout = "dwindle",
	},

	decoration = {
		rounding = 16,
		rounding_power = 2,

		-- Crystal UI transparency for windows
		active_opacity = 0.93,
		inactive_opacity = 0.85,

		shadow = {
			enabled = true,
			range = 20,
			render_power = 4,
			color = 0x44000000,
		},

		-- Liquid macOS-style multi-pass frosted glass blur
		blur = {
			enabled = true,
			size = 8,
			passes = 3,
			new_optimizations = true,
			ignore_opacity = true,
			xray = false,
			noise = 0.02,
			contrast = 0.95,
			brightness = 0.90,
			vibrancy = 0.25,
		},
	},

	animations = {
		enabled = true,
	},
})

-- Default curves and animations, see https://wiki.hypr.land/Configuring/Advanced-and-Cool/Animations/
hl.curve("easeOutQuint", { type = "bezier", points = { { 0.23, 1 }, { 0.32, 1 } } })
hl.curve("easeInOutCubic", { type = "bezier", points = { { 0.65, 0.05 }, { 0.36, 1 } } })
hl.curve("linear", { type = "bezier", points = { { 0, 0 }, { 1, 1 } } })
hl.curve("almostLinear", { type = "bezier", points = { { 0.5, 0.5 }, { 0.75, 1 } } })
hl.curve("quick", { type = "bezier", points = { { 0.15, 0 }, { 0.1, 1 } } })

-- Default springs
hl.curve("easy", { type = "spring", mass = 1, stiffness = 71.2633, dampening = 15.8273644 })

